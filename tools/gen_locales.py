    d = {}
    for row in T:
        assert row[0] not in d, row[0]
        d[row[0]] = row[i]
    with open(os.path.join(root, f'{loc}.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write('\n')
